"""On-disk format for frozen session days: file naming, hashing, read and write.

A *day file* is one JSON document holding the raw session records for one site and one
calendar day, exactly as the ACN-Data API returned them. Step indices are not stored:
the loader derives them at read time with `raw_session_to_standard`, so the same file
serves any (n_steps, dt_hours) horizon.

Two kinds of day file exist and they never mix:

  data/benchmark/caltech_2019-05-01.json            real, measured ACN-Data records
  data/benchmark/fixtures/SYNTHETIC_caltech_2019-05-01.json   generated, not measured

Every synthetic file carries `synthetic: true`, `data_source: "synthetic-fixture"`, a
`warning` string, a `SYNTHETIC_` filename prefix, and records whose sessionID and spaceID
start with `SYNTH-`. A number computed from a fixture is therefore traceable as synthetic
in any downstream table. Real files carry `synthetic: false` and the API base they came from.

`content_hash` is sha256 over the canonical JSON of the record list, so a frozen day can be
checked against its manifest entry without re-fetching.
"""

import hashlib
import json
from datetime import date, datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence

# Bump when the day-file or manifest layout changes incompatibly.
SCHEMA_VERSION = 1

BENCHMARK_DIR = Path(__file__).resolve().parent
