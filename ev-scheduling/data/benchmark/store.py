def day_filename(site_id: str, day_date: date, synthetic: bool = False) -> str:
    """Return the file name for one frozen day (e.g. 'caltech_2019-05-01.json')."""
    prefix = SYNTHETIC_PREFIX if synthetic else ""
    return f"{prefix}{site_id}_{day_date.isoformat()}.json"


def day_path(
    site_id: str,
    day_date: date,
    synthetic: bool = False,
    benchmark_dir: Optional[Path] = None,
) -> Path:
    """Return the full path for one frozen day.

    Real days live directly under benchmark_dir; fixtures live in its fixtures/ subfolder.

    Args:
        site_id: ACN-Data site (e.g. 'caltech').
        day_date: Calendar day.
        synthetic: True for a fixture path, False for a real frozen day.
        benchmark_dir: Root of the benchmark store. Defaults to data/benchmark/.

    Returns:
        Path to the day file. The file need not exist.
    """
    root = Path(benchmark_dir) if benchmark_dir is not None else BENCHMARK_DIR
    if synthetic:
        root = root / "fixtures"
    return root / day_filename(site_id, day_date, synthetic=synthetic)


def content_hash(records: Sequence[Dict[str, Any]]) -> str:
    """Return 'sha256:<hex>' over the canonical JSON of a record list.

    Keys are sorted and separators are tight, so the hash depends on the content and
    not on formatting. Non-JSON values (e.g. datetime) are hashed through str().
    """
    canonical = json.dumps(list(records), sort_keys=True, separators=(",", ":"), default=str)
    digest = hashlib.sha256(canonical.encode("utf-8")).hexdigest()
    return f"sha256:{digest}"


def utc_now_iso() -> str:
    """Return the current UTC time as an ISO-8601 string with a trailing Z."""
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def build_day_file(
    site_id: str,
    day_date: date,
    records: Sequence[Dict[str, Any]],
    data_source: str,
    synthetic: bool,
    fetched_at_utc: Optional[str] = None,
    extra: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """Assemble the JSON document for one frozen day.

    Args:
        site_id: ACN-Data site the records belong to.
        day_date: Calendar day (UTC midnight to midnight).
        records: Raw session dicts (ACN-Data keys: sessionID, spaceID, connectionTime,
            disconnectTime, kWhDelivered, and maxPower when available).
        data_source: SOURCE_ACN_API for measured data, SOURCE_SYNTHETIC for fixtures.
        synthetic: True only for generated data. Must be True iff data_source is
            SOURCE_SYNTHETIC; mismatches raise.
        fetched_at_utc: Fetch (or generation) timestamp. Defaults to now.
        extra: Additional provenance fields merged into the document (generator, seed, ...).

    Returns:
        A dict ready for json.dump, with record_count and content_hash filled in.

    Raises:
        ValueError: If synthetic and data_source disagree.
    """
    if synthetic != (data_source == SOURCE_SYNTHETIC):
        raise ValueError(
            f"synthetic={synthetic} contradicts data_source={data_source!r}; "
            "synthetic data must use data_source=SOURCE_SYNTHETIC"
        )

    payload: Dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "site_id": site_id,
        "date": day_date.isoformat(),
        "data_source": data_source,
        "synthetic": synthetic,
        "fetched_at_utc": fetched_at_utc or utc_now_iso(),
        "record_count": len(records),
        "content_hash": content_hash(records),
        "records": list(records),
    }
    if synthetic:
        payload["warning"] = SYNTHETIC_WARNING
    if extra:
        payload.update(extra)
    return payload


def write_day_file(path: Path, payload: Dict[str, Any], force: bool = False) -> Path:
    """Write one day file as pretty JSON, refusing to clobber an existing file.

    Args:
        path: Destination file.
        payload: Document from build_day_file.
        force: Overwrite an existing file instead of raising.

    Returns:
        The path written.

    Raises:
        FileExistsError: If path exists and force is False.
    """
    path = Path(path)
    if path.exists() and not force:
        raise FileExistsError(f"{path} already exists; pass --force to overwrite")
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2, sort_keys=True)
        f.write("\n")
    return path


def read_day_file(path: Path, verify_hash: bool = True) -> Dict[str, Any]:
    """Read and validate one day file.

    Args:
        path: Day file to read.
        verify_hash: Recompute content_hash over the records and compare.

    Returns:
        The parsed document.

    Raises:
        FileNotFoundError: If path does not exist.
        ValueError: If the schema version, required keys, or content hash do not check out.
    """
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(f"No frozen day file at {path}")
    with open(path, "r", encoding="utf-8") as f:
        payload = json.load(f)

    required = ("schema_version", "site_id", "date", "data_source", "synthetic", "records")
    missing = [k for k in required if k not in payload]
    if missing:
        raise ValueError(f"{path} is missing required key(s): {', '.join(missing)}")
    if payload["schema_version"] != SCHEMA_VERSION:
        raise ValueError(
            f"{path} has schema_version {payload['schema_version']}, expected {SCHEMA_VERSION}"
        )
    if not isinstance(payload["records"], list):
        raise ValueError(f"{path} 'records' must be a list")
    if payload["synthetic"] != (payload["data_source"] == SOURCE_SYNTHETIC):
        raise ValueError(
            f"{path} has synthetic={payload['synthetic']} but data_source="
            f"{payload['data_source']!r}; refusing to use an ambiguously labelled file"
        )
    if verify_hash and "content_hash" in payload:
        actual = content_hash(payload["records"])
        if actual != payload["content_hash"]:
            raise ValueError(
                f"{path} content_hash mismatch: file says {payload['content_hash']}, "
                f"records hash to {actual}. The file was edited after it was frozen."
            )
    return payload


def build_manifest_entry(payload: Dict[str, Any], path: Path) -> Dict[str, Any]:
    """Return the manifest row describing one written day file."""
    entry = {
        "date": payload["date"],
        "file": Path(path).name,
        "record_count": payload["record_count"],
        "content_hash": payload["content_hash"],
        "fetched_at_utc": payload["fetched_at_utc"],
    }
    for key in ("profile", "notes", "seed", "congested", "demand_ratio", "requested_energy_kwh",
                "deliverable_upper_bound_kwh"):
        if key in payload:
            entry[key] = payload[key]
    return entry


def write_manifest(
    path: Path,
    site_id: str,
    entries: Sequence[Dict[str, Any]],
    data_source: str,
    synthetic: bool,
    extra: Optional[Dict[str, Any]] = None,
) -> Path:
    """Write the manifest for a benchmark folder, sorted by date.

    The manifest records what is frozen, when, how many records per day, and the content
    hash of each day, so a later reader can tell whether the committed data is the data
    the paper's numbers came from.
    """
    rows = sorted(entries, key=lambda e: str(e["date"]))
    payload: Dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "site_id": site_id,
        "data_source": data_source,
        "synthetic": synthetic,
        "written_at_utc": utc_now_iso(),
        "day_count": len(rows),
        "total_records": sum(int(r.get("record_count", 0)) for r in rows),
        "days": rows,
    }
    if synthetic:
        payload["warning"] = SYNTHETIC_WARNING
    if extra:
        payload.update(extra)

    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2, sort_keys=True)
        f.write("\n")
    return path


def read_manifest(path: Path) -> Dict[str, Any]:
    """Read a manifest file.

    Raises:
        FileNotFoundError: If the manifest does not exist.
    """
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(f"No manifest at {path}")
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def deliverable_upper_bound_kwh(
    sessions: Sequence[Any],
    cap_kw: float,
    n_steps: int,
    dt_hours: float,
) -> float:
    """Upper bound on the energy any feasible schedule can deliver in one day (kWh).

    At each step the site can deliver at most the site cap, and at most the summed
    per-session power limits of the sessions plugged in at that step. Summing the
    smaller of the two over all steps bounds every feasible schedule from above, so
    a day whose requested energy exceeds this bound must end with unmet energy
    regardless of the scheduler. Used to label congested fixture days and to assert
    in tests that those days really are congested.

    Args:
        sessions: Session objects with arrival_idx, departure_idx, max_power_kw.
        cap_kw: Site power cap (kW).
        n_steps: Horizon length in steps.
        dt_hours: Step duration in hours.

    Returns:
        Maximum deliverable energy in kWh.
    """
    total = 0.0
    for t in range(n_steps):
        available_kw = sum(
            float(s.max_power_kw) for s in sessions if s.arrival_idx <= t < s.departure_idx
        )
        total += min(float(cap_kw), available_kw) * dt_hours
    return total
