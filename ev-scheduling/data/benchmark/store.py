SYNTHETIC_PREFIX = "SYNTHETIC_"

# Values of the day file's "data_source" field.
SOURCE_ACN_API = "acn-data-api"
SOURCE_SYNTHETIC = "synthetic-fixture"

SYNTHETIC_WARNING = (
    "SYNTHETIC DATA. Generated by data/benchmark/fixtures_gen.py for offline testing. "
    "These sessions were never measured. Never report a number computed from this file."
)

